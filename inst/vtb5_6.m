    'style','slider',...
	'position',[.25 0 .5 .025],...
	'units','normalized',...
	'min',-90,'max',90,'value',30);
sli_elv=uicontrol(gcf,...
    'style','slider',...
	'position',[.0 .25 .0185 .5],...
	'units','normalized',...
	'min',0,'max',90,'value',30);
setview=@(~,~) set(ax,'view',[get(sli_azm,'value'),get(sli_elv,'value')]);
set(sli_azm,'callback',setview)
